import { expect, test } from '@playwright/test'

test('selects and drags a node, edits its note, and restores the edit', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('#graph')).toHaveAttribute('data-nodes', '5')
  const coordinates = () => page.evaluate(() => (window as any).flowCanvas.canvasCoordinates('relay') as [number, number])
  let [x, y] = await coordinates()
  await page.mouse.click(x, y)
  await expect(page.getByRole('heading', { name: 'Relay wallet', exact: true })).toBeVisible()
  await page.mouse.move(x, y)
  await page.mouse.down()
  const dragStarted = performance.now()
  await page.mouse.move(x, y + 60, { steps: 8 })
  await page.mouse.up()
  await expect.poll(async () => (await coordinates())[1]).not.toBe(y)
  console.log('Node drag and render: ' + Math.round(performance.now() - dragStarted) + ' ms')
  await page.getByLabel('Node note').fill('Note edited in browser')
  await page.getByLabel('Node note').press('Tab')
  await page.reload()
  await expect(page.locator('#graph')).toHaveAttribute('data-nodes', '5')
  ;[x, y] = await coordinates()
  await page.mouse.click(x, y)
  await expect(page.getByLabel('Node note')).toHaveValue('Note edited in browser')
  await page.getByRole('button', { name: 'Agent chat' }).click()
  await expect(page.locator('#agent-context')).toContainText('Relay wallet')
  expect(errors).toEqual([])
})

