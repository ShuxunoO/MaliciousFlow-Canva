import { expect, test } from '@playwright/test'

test('selects and drags a node, edits its note, and restores the edit', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('#graph')).toHaveAttribute('data-nodes', '5')
  const coordinates = () => page.evaluate(() => (window as any).flowCanvas.canvasCoordinates('relay') as [number, number])
  let [x, y] = await coordinates()
  await page.mouse.click(x, y)
  await expect(page.getByRole('heading', { name: 'Relay wallet', exact: true })).toBeVisible()
  await page.mouse.move(x, y)
  await page.mouse.down()
  await page.mouse.move(x, y + 60, { steps: 8 })
  await page.mouse.up()
  await expect.poll(async () => (await coordinates())[1]).not.toBe(y)
  await page.getByLabel('Node note').fill('Note edited in browser')
  await page.getByLabel('Node note').press('Tab')
  await page.reload()
  await expect(page.locator('#graph')).toHaveAttribute('data-nodes', '5')
  ;[x, y] = await coordinates()
  await page.mouse.click(x, y)
  await expect(page.getByLabel('Node note')).toHaveValue('Note edited in browser')
  await page.getByRole('button', { name: 'Agent chat' }).click()
  await expect(page.locator('#agent-context')).toContainText('Relay wallet')
  expect(errors).toEqual([])
})

test('navigates between evidence and graph, changes the line bend, and filters by time', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('#graph')).toHaveAttribute('data-edges', '5')
  await page.screenshot({ path: test.info().outputPath('canvas.png') })
  await page.getByRole('button', { name: 'D-3', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Transaction details' })).toBeVisible()
  const handle = page.getByRole('button', { name: 'Drag transaction edge' })
  await expect(handle).toBeVisible()
  const rect = await handle.boundingBox()
  if (!rect) throw new Error('Missing edge handle')
  const x = rect.x + rect.width / 2
  const y = rect.y + rect.height / 2
  await page.mouse.move(x, y)
  await page.mouse.down()
  await page.mouse.move(x + 36, y + 36, { steps: 8 })
  await page.mouse.up()
  await expect.poll(() => page.evaluate(() => Object.keys(JSON.parse(localStorage.getItem('flow-edits:canvas-workshop') ?? '{}').bends ?? {}).length)).toBe(1)
  await page.getByRole('button', { name: 'Evidence D-3' }).click()
  await expect(page.getByRole('heading', { name: 'Evidence D-3' })).toBeVisible()
  await page.getByLabel('End date UTC').fill('2020-09-26')
  await expect(page.locator('#status')).toContainText('3 transfers')
})

test('filters by address, explores node balances and connects two nodes', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('html')).toHaveAttribute('lang', 'en')
  await expect(page.locator('#graph')).toHaveAttribute('data-nodes', '5')
  await expect(page.locator('body')).not.toContainText(/\p{Script=Han}/u)
  await page.getByLabel('Address or entity').selectOption('alpha')
  await expect(page.locator('#graph')).toHaveAttribute('data-nodes', '2')
  await expect(page.locator('#status')).toContainText('1 transfer')
  await page.getByRole('button', { name: 'Reset filters' }).click()
  await expect(page.locator('#graph')).toHaveAttribute('data-nodes', '5')

  const graphPoint = (id: string) => page.evaluate(item => (window as any).flowCanvas.canvasCoordinates(item) as [number, number], id)
  await page.mouse.click(...await graphPoint('relay'))
  await expect(page.getByRole('table', { name: 'Token flows and balances' })).toContainText('$6800')
  await page.getByRole('button', { name: 'Agent chat' }).click()
  await page.getByLabel('Ask about this selection').fill('What is the ETH balance?')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.locator('#agent-messages')).toContainText('19 ETH · $6800')
  await page.getByRole('button', { name: 'Agent chat' }).click()

  await page.getByRole('button', { name: 'Connect', exact: true }).click()
  await expect(page.locator('#status')).toContainText('Choose the destination')
  await page.mouse.click(...await graphPoint('beta'))
  await expect(page.locator('#graph')).toHaveAttribute('data-edges', '6')
  await expect(page.locator('#status')).toContainText('6 transfers')
  await page.getByRole('button', { name: 'Undo', exact: true }).click()
  await expect(page.locator('#graph')).toHaveAttribute('data-edges', '5')
})

test('toggles the branch from the node card and preserves its position', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('#graph')).toHaveAttribute('data-nodes', '5')
  const port = await page.evaluate(async () => {
    const state = await (window as any).maliciousFlow.set_view()
    const [x, y] = (window as any).flowCanvas.canvasCoordinates('relay')
    return [x + 112 * state.zoom, y] as [number, number]
  })
  await page.mouse.click(...port)
  await expect(page.locator('#status')).toContainText('3 transfers')
  await expect(page.getByRole('button', { name: 'Expand outflow' })).toBeVisible()
})
