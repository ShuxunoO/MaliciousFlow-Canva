import { expect, test } from '@playwright/test'

test('selects and drags a node, edits its note, and restores the edit', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await expect(page.locator('#graph')).toHaveAttribute('data-nodes', '5')
  const coordinates = () => page.evaluate(() => (window as any).flowCanvas.canvasCoordinates('relay') as [number, number])
  let [x, y] = await coordinates()
  await page.mouse.click(x, y)
  await expect(page.getByRole('heading', { name: '中转钱包', exact: true })).toBeVisible()
  await page.mouse.move(x, y)
  await page.mouse.down()
  await page.mouse.move(x, y + 60, { steps: 8 })
  await page.mouse.up()
  await expect.poll(async () => (await coordinates())[1]).not.toBe(y)
  await page.getByLabel('节点备注').fill('浏览器测试备注')
  await page.getByLabel('节点备注').press('Tab')
  await page.reload()
  await expect(page.locator('#graph')).toHaveAttribute('data-nodes', '5')
  ;[x, y] = await coordinates()
  await page.mouse.click(x, y)
  await expect(page.getByLabel('节点备注')).toHaveValue('浏览器测试备注')
  await page.getByRole('button', { name: 'Agent 对话' }).click()
  await expect(page.locator('#agent-context')).toContainText('中转钱包')
  expect(errors).toEqual([])
})

test('navigates between evidence and graph, changes the line bend, and filters by time', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('#graph')).toHaveAttribute('data-edges', '5')
  await page.screenshot({ path: test.info().outputPath('canvas.png') })
  await page.getByRole('button', { name: 'D-3', exact: true }).click()
  await expect(page.getByRole('heading', { name: '交易明细' })).toBeVisible()
  const handle = page.getByRole('button', { name: '拖动交易线' })
  await expect(handle).toBeVisible()
  const rect = await handle.boundingBox()
  if (!rect) throw new Error('Missing edge handle')
  const x = rect.x + rect.width / 2
  const y = rect.y + rect.height / 2
  await page.mouse.move(x, y)
  await page.mouse.down()
  await page.mouse.move(x + 36, y + 36, { steps: 8 })
  await page.mouse.up()
  await expect.poll(() => page.evaluate(() => Object.keys(JSON.parse(localStorage.getItem('flow-edits:canvas-workshop') ?? '{}').bends ?? {}).length)).toBe(1)
  await page.getByRole('button', { name: '证据 D-3' }).click()
  await expect(page.getByRole('heading', { name: '证据 D-3' })).toBeVisible()
  await page.getByLabel('结束日期 UTC').fill('2020-09-26')
  await expect(page.locator('#status')).toContainText('3 笔转账')
})
