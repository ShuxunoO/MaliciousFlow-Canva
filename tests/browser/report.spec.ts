import { expect, test } from '@playwright/test'

test('browses the timeline, temporarily reveals evidence, edits a draft and publishes a conclusion', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('#graph')).toHaveAttribute('data-nodes', '5')
  await page.getByLabel('结束日期 UTC').fill('2020-09-26')
  await expect(page.locator('#status')).toContainText('3 笔转账')
  await page.getByRole('button', { name: '交易时间线' }).click()
  await page.getByRole('button', { name: 'D-6', exact: true }).click()
  await expect(page.getByRole('heading', { name: '交易明细' })).toBeVisible()
  await expect(page.locator('#status')).toContainText('4 笔转账')
  await page.getByRole('button', { name: '证据 D-6' }).click()
  await expect(page.getByRole('heading', { name: '证据 D-6' })).toBeVisible()
  await page.getByRole('button', { name: '返回原视图' }).click()
  await expect(page.locator('#status')).toContainText('3 笔转账')
  await page.getByRole('button', { name: '起草', exact: true }).click()
  await page.getByLabel('目标章节').selectOption('entry')
  await page.getByLabel('草稿', { exact: true }).fill('依据 D-1 核对首次转账')
  await page.getByLabel('引用（每行一个）').fill('D-1')
  await page.getByRole('button', { name: '保存草稿' }).click()
  await page.getByRole('button', { name: '编辑草稿' }).click()
  await page.getByLabel('草稿', { exact: true }).fill('依据 D-1 核对 18.5 ETH')
  await page.getByRole('button', { name: '保存草稿' }).click()
  await page.getByRole('button', { name: '预览结论' }).click()
  await expect(page.getByRole('heading', { name: '结论变更预览' })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('report-review.png') })
  await page.getByRole('button', { name: '确认更新' }).click()
  await expect(page.getByText('结论版本 1')).toBeVisible()
  await page.reload()
  await expect(page.getByText('结论版本 1')).toBeVisible()
})
