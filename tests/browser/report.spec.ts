import { expect, test } from '@playwright/test'

test('browses the timeline, temporarily reveals evidence, edits a draft and publishes a conclusion', async ({ page }) => {
  await page.goto('/#chart/canvas-workshop')
  await expect(page.locator('#graph')).toHaveAttribute('data-nodes', '5')
  await page.getByLabel('End date UTC').fill('2020-09-26')
  await expect(page.locator('#status')).toContainText('3 transfers')
  await page.getByRole('button', { name: 'Timeline' }).click()
  await page.getByRole('button', { name: 'D-6', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Transaction details' })).toBeVisible()
  await expect(page.locator('#status')).toContainText('4 transfers')
  await page.getByRole('button', { name: 'Evidence D-6' }).click()
  await expect(page.getByRole('heading', { name: 'Evidence D-6' })).toBeVisible()
  await page.getByRole('button', { name: 'Return to previous view' }).click()
  await expect(page.locator('#status')).toContainText('3 transfers')
  await page.getByRole('button', { name: 'New draft', exact: true }).click()
  await page.getByLabel('Target chapter').selectOption('entry')
  await page.getByLabel('Draft', { exact: true }).fill('First transfer verified against D-1')
  await page.getByLabel('References (one per line)').fill('D-1')
  await page.getByRole('button', { name: 'Save draft' }).click()
  await page.getByRole('button', { name: 'Edit draft' }).click()
  await page.getByLabel('Draft', { exact: true }).fill('Verified 18.5 ETH against D-1')
  await page.getByRole('button', { name: 'Save draft' }).click()
  await page.getByRole('button', { name: 'Review conclusion' }).click()
  await expect(page.getByRole('heading', { name: 'Conclusion review' })).toBeVisible()
  await page.screenshot({ path: test.info().outputPath('report-review.png') })
  await page.getByRole('button', { name: 'Publish' }).click()
  await expect(page.getByText('Conclusion version 1')).toBeVisible()
  await page.reload()
  await expect(page.getByText('Conclusion version 1')).toBeVisible()
})
